"""Emit a pipelined Verilog EML tree from an 'e(L,R)' witness string.

Every internal node is one eml_cell instance.  Leaves are the constant 1
(Q16.16 0x00010000) or the inputs x0/x1.  Inputs that arrive early at a node
are delayed with shift registers so both operands of every cell come from the
same sample, giving a fully pipelined tree with one result per clock.

Also provides eval_tree_q(), the bit-exact tree model built on eml_model.eml_q.

    python fpga/gen_tree.py      # writes rtl/eml_tree_{mul,add,sub}.v
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
for p in (str(HERE), str(ROOT)):
    if p not in sys.path:
        sys.path.insert(0, p)

import eml_model as M

from benchmarks.perm_det_eml import parse, size
from benchmarks.perm_det_gadgets import PROD, SUB, SUM, S

CELL_LATENCY = 10  # eml_cell: inputs sampled at edge 0, out valid after edge 9

TREES = {
    "mul": S(PROD("x0", "x1")),   # x0 * x1, 8 nodes
    "add": SUM("x0", "x1"),       # x0 + x1, 9 nodes
    "sub": SUB("x0", "x1"),       # x0 - x1, 5 nodes
}


def eval_tree_q(t, env: dict):
    """Bit-exact Q16.16 evaluation; returns (value, any_invalid)."""
    if isinstance(t, str):
        v = np.full_like(next(iter(env.values())), M.ONE) if t == "1" else env[t]
        return v, np.zeros(v.shape, bool)
    a, ia = eval_tree_q(t[0], env)
    b, ib = eval_tree_q(t[1], env)
    v, inv = M.eml_q(a, b)
    return v, ia | ib | inv


def emit(name: str, witness: str) -> tuple[str, int, int]:
    tree = parse(witness)
    lines: list[str] = []
    counter = [0]

    def delayed(sig: str, n: int) -> str:
        if n == 0:
            return sig
        k = counter[0]
        counter[0] += 1
        d = f"d{k}"
        lines.append(f"    reg signed [31:0] {d} [0:{n - 1}];")
        lines.append("    integer i_" + d + ";")
        lines.append("    always @(posedge clk) begin")
        lines.append(f"        {d}[0] <= {sig};")
        lines.append(f"        for (i_{d} = 1; i_{d} < {n}; i_{d} = i_{d} + 1)"
                     f" {d}[i_{d}] <= {d}[i_{d} - 1];")
        lines.append("    end")
        return f"{d}[{n - 1}]"

    def build(t) -> tuple[str, int | None]:
        """Return (signal, ready_time); ready_time None for the constant."""
        if isinstance(t, str):
            return ("32'sh0001_0000", None) if t == "1" else (t, 0)
        a, ta = build(t[0])
        b, tb = build(t[1])
        tm = max(x for x in (ta, tb, 0) if x is not None)
        if ta is not None:
            a = delayed(a, tm - ta)
        if tb is not None:
            b = delayed(b, tm - tb)
        k = counter[0]
        counter[0] += 1
        o = f"n{k}"
        lines.append(f"    wire signed [31:0] {o}; wire {o}_inv;")
        lines.append(f"    eml_cell c{k}(.clk(clk), .in_valid(1'b1), .x({a}), .y({b}),"
                     f" .out_valid(), .out({o}), .invalid({o}_inv));")
        return o, tm + CELL_LATENCY

    root, lat = build(tree)
    header = [
        f"// Generated by fpga/gen_tree.py: {name} as a pure EML tree,",
        f"// {size(tree)} eml_cell nodes, latency {lat} cycles.",
        f"// witness: {witness}",
        f"module eml_tree_{name} (",
        "    input  wire               clk,",
        "    input  wire               in_valid,",
        "    input  wire signed [31:0] x0,",
        "    input  wire signed [31:0] x1,",
        "    output wire               out_valid,",
        "    output wire signed [31:0] out,",
        "    output wire               invalid",
        ");",
        f"    reg [{lat - 1}:0] v = 0;",
        f"    always @(posedge clk) v <= {{v[{lat - 2}:0], in_valid}};",
        f"    assign out_valid = v[{lat - 1}];",
    ]
    footer = [f"    assign out = {root};", f"    assign invalid = {root}_inv;",
              "endmodule", ""]
    return "\n".join(header + lines + footer), size(tree), lat


def main() -> None:
    for name, w in TREES.items():
        src, n, lat = emit(name, w)
        (HERE / "rtl" / f"eml_tree_{name}.v").write_text(src)
        print(f"{name}: {n} nodes, latency {lat}")


if __name__ == "__main__":
    main()
